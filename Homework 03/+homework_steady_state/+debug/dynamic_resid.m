function [lhs, rhs] = dynamic_resid(y, x, params, steady_state)
T = NaN(4, 1);
lhs = NaN(5, 1);
rhs = NaN(5, 1);
T(1) = params(2)*y(3)^params(3);
T(2) = y(7)^(1-params(3));
T(3) = params(4)*1/y(11);
T(4) = params(3)*y(14)/y(8)+1-params(5);
lhs(1) = y(9);
rhs(1) = T(1)*T(2);
lhs(2) = params(1)*y(6)/(1-y(7));
rhs(2) = y(9)*(1-params(3))/y(7);
lhs(3) = 1/y(6);
rhs(3) = T(3)*T(4);
lhs(4) = y(8);
rhs(4) = y(3)*(1-params(5))+y(10);
lhs(5) = y(9);
rhs(5) = y(6)+y(10);
end
